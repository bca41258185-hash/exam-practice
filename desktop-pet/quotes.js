// 一段帶出處的話 → 要一句一句說的陣列
function verseLines(v) {
  if (!v.by) return v.lines;
  const who = v.by.replace(/《.*》/, '') || v.by;   // 泡泡放不下書名時只報作者；只有書名的（《周易》）就報書名
  return [...v.lines, '——' + who];
}

